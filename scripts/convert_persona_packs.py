#!/usr/bin/env python3
"""把人设原文细拆为 PERSONA_PACK 并写回 modules/*.md。"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "plugins"))

spec = importlib.util.spec_from_file_location(
    "persona_pack", ROOT / "plugins/group_world_state/persona_pack.py"
)
pp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pp)


def F(key: str, value: str, note: str = "") -> dict:
    return {"key": key, "value": value, "note": note}


def I(value: str, note: str = "", key: str = "") -> dict:
    return {"key": key, "value": value, "note": note}


def write_pack(character: str, module: str, pack: dict) -> None:
    pack = dict(pack)
    pack["module"] = module
    text = pp.format_persona_pack(pack)
    path = ROOT / "data/persona" / character / "modules" / f"{character}_{module}.md"
    path.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size} bytes)")


